"""Two-form node descriptions for the DRAG tree, retrieval-optimized.

The existing ``rag_lib`` descriptor produces a single ``description`` string
written in regulatory-documentation style. For QASPER scientific papers
this trades retrieval signal for human readability — and the benchmark
shows DRAG losing to flat hybrid as a result.

This module replaces leaf+parent annotation for ``bench_drag`` ONLY, with
two complementary outputs per node:

    abstract  1-2 sentences, paraphrase-friendly  -> dense embedding
    bullets   5-8 short facts, BM25-friendly      -> sparse / keywords

``bench_raptor`` keeps its raw-text leaves + the old summarizer prompt on
parents, so we get a controlled comparison: DRAG-old vs DRAG-rich at
identical tree shape, with RAPTOR sitting fixed as the reference point.
"""

from __future__ import annotations

from typing import Callable

from pydantic import BaseModel, Field

from .datasets import Paragraph


LLMSummarizer = Callable[..., tuple[str, str]]


class RichDescriptorOutput(BaseModel):
    """LLM output for a LEAF node. Two-form: abstract (dense) + bullets (BM25)."""

    abstract: str = Field(
        description=(
            "1-2 sentence summary of the fragment's content, written for "
            "dense-embedding retrieval (not for humans). Use natural "
            "paraphrasable phrasing. Do NOT start with 'this paragraph', "
            "'the authors', 'this paper', 'we', 'our'."
        ),
    )
    bullets: list[str] = Field(
        description=(
            "5-8 short BM25-friendly facts. Each bullet is one specific "
            "phrase under 12 words: a method name, dataset, model, number, "
            "finding, term, or entity. Preserve acronyms verbatim (BLEU, "
            "BERT, F1, GLUE — not 'the BLEU score'). Preserve numbers "
            "with their units. One concept per bullet, no filler."
        ),
    )


class ParentAbstractOutput(BaseModel):
    """LLM output for a PARENT node — abstract only.

    Bullets at parent level are NOT generated by the LLM. They are the
    union of child bullets (dedup, capped). This matches rag_lib's
    semantic (`build_tree.create_parent_node_and_update_children` sets
    `keywords=all_child_keywords`) and avoids paying the LLM to redo
    work that a dedup pass does more reliably.
    """

    abstract: str = Field(
        description=(
            "1-2 sentence higher-level synthesis of the children. Captures "
            "the overarching theme connecting them, NOT a list of what "
            "each child says. Dense-embedding target. Natural phrasing. "
            "Do NOT start with 'this section', 'the authors', 'we', 'our'."
        ),
    )


LEAF_PROMPT = """# Role
You annotate fragments of academic NLP / ML / scientific papers for a hybrid retrieval system (dense + BM25). Your output is consumed by a retriever, NOT by humans — readability is irrelevant; retrievability is everything.

# Input
"Raw Page Content": a single paragraph from a scientific paper.

# Task
Produce TWO complementary representations of the fragment's content.

## 1. abstract (1-2 sentences)
- Dense-embedding target. A paraphrase of the actual content — what it is ABOUT and CLAIMS — in natural phrasing that a question over this content would semantically rhyme with.
- NO stage-setting: never write "this paragraph", "this section", "the authors", "this paper", "we", "our". Speak about the SUBJECT, not the document.
- NO filler intros like "It is shown that…", "It describes…", "It discusses…".

## 2. bullets (5-8 items)
- BM25 target. Each bullet is ONE high-entropy phrase, under 12 words.
- Preserve acronyms VERBATIM and standalone: BLEU, F1, BERT, GLUE, GPT-3, SST-2 — not "the BLEU metric".
- Preserve numbers with units and context: "62.3 F1 on SST-2", "12-layer transformer", "+2.1 BLEU".
- Include: method names, model names, dataset names, task names, specific findings, technical terms, entities.
- Exclude: generic prose, filler words, full sentences. No bullet should read like English narrative.

# Hard rules
- abstract and bullets must NOT repeat the same phrase verbatim.
- If the input is empty or only artifacts (citations only, table noise), set abstract to a one-line plain description of what's there and return [] for bullets.

# Output
JSON only — no markdown code blocks, no commentary:
{"abstract": "<one line>", "bullets": ["<phrase>", "<phrase>", ...]}
"""


PARENT_PROMPT = """# Role
You aggregate child-node annotations from a scientific-paper tree for the dense side of a hybrid retrieval system. Each child gives you (abstract, bullets).

# Input
"Child Metadata": a numbered list of child abstracts and bullets.

# Task
Produce ONE higher-level abstract (1-2 sentences) that CONNECTS the children. Synthesize the theme that unites them — NOT a concatenation, NOT "the section covers X and Y and Z".

# Rules
- Dense-embedding target. Natural, paraphrase-friendly phrasing.
- NO stage-setting: never write "this section", "the authors", "this paper", "we", "our".
- Stay in the SAME domain as the children — do not introduce concepts no child mentioned.
- Bullets at this level are NOT your job: a separate aggregation step unions the children's bullets directly.

# Output
JSON only — no markdown code blocks, no commentary:
{"abstract": "<one line>"}
"""


# Used by RAPTOR-style parents where children carry raw text (no bullets to
# union). The LLM has to extract bullets from the children's abstract/text
# directly, in addition to synthesizing the parent abstract.
FULL_PARENT_PROMPT = """# Role
You aggregate child-node annotations from a scientific-paper tree for a hybrid retrieval system (dense + BM25). Each child gives you an abstract (which may be raw paragraph text or a prior synthesized abstract) and optionally some bullets.

# Input
"Child Metadata": a numbered list of children.

# Task
Produce a parent annotation with TWO complementary outputs.

## 1. abstract (1-2 sentences)
- Higher-level theme that CONNECTS the children — NOT a concatenation, NOT "the section covers X and Y".
- Dense-embedding target. Natural, paraphrase-friendly phrasing.
- NO stage-setting: never write "this section", "the authors", "this paper", "we", "our".

## 2. bullets (5-10 items)
- BM25 target. Each bullet is ONE high-entropy phrase under 12 words.
- Preserve acronyms verbatim and standalone (BLEU, BERT, F1, GLUE — not "the BLEU metric").
- Preserve numbers with units and context ("62.3 F1 on SST-2", "12-layer transformer").
- Include: method names, model names, dataset names, task names, findings, entities.
- Exclude: generic prose, filler words, full sentences.
- If a term appears across multiple children, include it ONCE.

# Hard rules
- Stay in the SAME domain as the children — do not introduce concepts no child mentioned.
- abstract and bullets must NOT repeat the same phrase verbatim.

# Output
JSON only — no markdown code blocks, no commentary:
{"abstract": "<one line>", "bullets": ["<phrase>", "<phrase>", ...]}
"""


def _union_child_bullets(
    child_descriptions: list[tuple[str, list[str]]], cap: int = 10
) -> list[str]:
    """Dedup-preserving union of child bullets, capped.

    Mirrors `rag_lib/build_tree.py`'s `all_child_keywords = list(set(...))`
    semantic but keeps first-seen order so the most consistent terms
    bubble up across rebuilds.
    """
    seen: set[str] = set()
    out: list[str] = []
    for _, bs in child_descriptions:
        for b in bs:
            key = b.strip().lower()
            if not key or key in seen:
                continue
            seen.add(key)
            out.append(b)
            if len(out) >= cap:
                return out
    return out


def _truncate(text: str, max_chars: int = 800) -> str:
    text = text.strip()
    if len(text) <= max_chars:
        return text
    return text[:max_chars].rsplit(" ", 1)[0] + " ..."


def describe_leaf_rich(
    paragraph: Paragraph, summarizer: LLMSummarizer | None
) -> RichDescriptorOutput:
    """Annotate a single paragraph with (abstract, bullets).

    When ``summarizer`` is None (e.g. ``--no-llm`` / smoke test), fall back
    to truncated raw text as abstract and empty bullets. Same fallback
    semantics as the original ``_describe_leaf``.
    """
    if summarizer is None:
        return RichDescriptorOutput(
            abstract=_truncate(paragraph.text), bullets=[]
        )
    messages = [
        {"role": "system", "content": LEAF_PROMPT},
        {"role": "user", "content": f"Raw Page Content:\n{paragraph.text}"},
    ]
    for _ in range(3):
        try:
            output_str, _ = summarizer(messages, RichDescriptorOutput)
            return RichDescriptorOutput.model_validate_json(output_str)
        except Exception:
            continue
    return RichDescriptorOutput(abstract=_truncate(paragraph.text), bullets=[])


def describe_parent_with_bullets(
    child_descriptions: list[tuple[str, list[str]]],
    summarizer: LLMSummarizer | None,
) -> RichDescriptorOutput:
    """Parent annotation where the LLM produces BOTH abstract and bullets.

    Use this for RAPTOR-style trees whose leaves carry raw paragraph text
    (no bullets to union upward). The LLM extracts high-entropy terms from
    the children's text in the same call that synthesizes the abstract.

    DRAG, where leaves already have LLM-generated bullets, uses
    ``describe_parent_rich`` instead (cheaper, more faithful to the
    original tree-building semantic).
    """
    if summarizer is None:
        merged_abstract = " | ".join(a for a, _ in child_descriptions if a)
        merged_bullets = _union_child_bullets(child_descriptions)
        return RichDescriptorOutput(
            abstract=_truncate(merged_abstract), bullets=merged_bullets
        )
    combined = "\n\n".join(
        f"Child #{i}\nAbstract: {abstract}\nBullets: {'; '.join(child_bullets) or '(none)'}"
        for i, (abstract, child_bullets) in enumerate(child_descriptions, 1)
    )
    messages = [
        {"role": "system", "content": FULL_PARENT_PROMPT},
        {"role": "user", "content": f"Child Metadata:\n{combined}"},
    ]
    for _ in range(3):
        try:
            output_str, _ = summarizer(messages, RichDescriptorOutput)
            return RichDescriptorOutput.model_validate_json(output_str)
        except Exception:
            continue
    merged_abstract = " | ".join(a for a, _ in child_descriptions if a)
    merged_bullets = _union_child_bullets(child_descriptions)
    return RichDescriptorOutput(
        abstract=_truncate(merged_abstract), bullets=merged_bullets
    )


def describe_parent_rich(
    child_descriptions: list[tuple[str, list[str]]],
    summarizer: LLMSummarizer | None,
) -> RichDescriptorOutput:
    """Aggregate child (abstract, bullets) pairs into a parent annotation.

    LLM is asked ONLY for the abstract (one synthesizing sentence). Bullets
    are the dedup-union of child bullets — same pattern as
    ``rag_lib/build_tree.py``'s ``all_child_keywords``, and cheaper / less
    lossy than asking the LLM to redo the dedup.

    Without an LLM: concatenate child abstracts as the abstract fallback,
    plus the same union for bullets. Returned as a ``RichDescriptorOutput``
    so the rest of the pipeline doesn't care which path produced it.
    """
    bullets = _union_child_bullets(child_descriptions)

    if summarizer is None:
        merged_abstract = " | ".join(a for a, _ in child_descriptions if a)
        return RichDescriptorOutput(
            abstract=_truncate(merged_abstract), bullets=bullets
        )

    combined = "\n\n".join(
        f"Child #{i}\nAbstract: {abstract}\nBullets: {'; '.join(child_bullets) or '(none)'}"
        for i, (abstract, child_bullets) in enumerate(child_descriptions, 1)
    )
    messages = [
        {"role": "system", "content": PARENT_PROMPT},
        {"role": "user", "content": f"Child Metadata:\n{combined}"},
    ]
    for _ in range(3):
        try:
            output_str, _ = summarizer(messages, ParentAbstractOutput)
            parent_out = ParentAbstractOutput.model_validate_json(output_str)
            return RichDescriptorOutput(abstract=parent_out.abstract, bullets=bullets)
        except Exception:
            continue
    merged_abstract = " | ".join(a for a, _ in child_descriptions if a)
    return RichDescriptorOutput(
        abstract=_truncate(merged_abstract), bullets=bullets
    )
